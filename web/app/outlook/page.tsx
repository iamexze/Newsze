import Link from "next/link";
import { TREES, ENGINE } from "@/lib/outlook";
import { byId, chg } from "@/lib/data";
import { num } from "@/lib/format";
import { SectionHead, Notice, Delta, Spark } from "@/components/Bits";
import Tree from "@/components/Tree";
import { CountUp } from "@/components/Motion";
import T from "@/components/T";

export const metadata = {
  title: "Outlook",
  description: "Branching possibility trees — if it goes up it may break down, if it breaks down it may go up. Every branch with its probability and the basis for it.",
};

export default function Outlook() {
  const branches = TREES.reduce((a, t) => a + t.root.length +
    t.root.reduce((b, r) => b + (r.children?.length ?? 0) +
      (r.children?.reduce((c, x) => c + (x.children?.length ?? 0), 0) ?? 0), 0), 0);

  return (
    <>
      <section className="band" style={{ paddingBlock: "46px 40px" }}>
        <div className="wrap">
          <div className="kicker accent">Outlook · possibility trees</div>
          <h1 className="reveal" style={{ fontSize: "clamp(32px,5.4vw,60px)", marginTop: 10, maxWidth: 1020 }}>
            <T en="If it goes up it may break down. If it breaks down it may go up. Here are both, with the odds."
               hi="चढ़े तो टूट सकता है, टूटे तो चढ़ सकता है। दोनों रास्ते, संभावनाओं के साथ।" />
          </h1>
          <p className="sub reveal d1" style={{ fontSize: 17, maxWidth: 810, marginTop: 14, lineHeight: 1.55 }}>
            Markets do not have one outcome, they have a tree of them. Each branch here carries a
            probability and — crucially — the <strong>basis</strong> for that probability: either
            the option market&apos;s own pricing, or the historical frequency in our corpus. Where
            the two disagree, we show both.
          </p>
          <div className="grid g4 mt32" style={{ gap: 20 }}>
            <div className="reveal"><div className="figure lg"><CountUp value={TREES.length} /></div>
              <div className="statlbl">Instruments mapped</div></div>
            <div className="reveal d1"><div className="figure lg"><CountUp value={branches} /></div>
              <div className="statlbl">Branches with a stated probability</div></div>
            <div className="reveal d2"><div className="figure lg">46%</div>
              <div className="statlbl">The single most likely Nifty path — less likely than not</div></div>
            <div className="reveal d3"><div className="figure lg">0</div>
              <div className="statlbl">Numbers on this page generated by a language model</div></div>
          </div>
        </div>
      </section>

      <div className="wrap" style={{ paddingTop: 28 }}>
        <div className="breadcrumb"><Link href="/">Today</Link> / Outlook</div>

        <div className="stack mb32" style={{ gap: 20 }}>
          {TREES.map((t) => {
            const inst = byId(t.instrument);
            return (
              <section key={t.slug} className="card reveal">
                <div className="between mb16" style={{ alignItems: "flex-start" }}>
                  <div className="min0">
                    <div className="row" style={{ gap: 8 }}>
                      <span className="chip a">{t.horizon}</span>
                      <span className="meta">{t.asOf}</span>
                    </div>
                    <h2 style={{ fontSize: 26, marginTop: 8 }}>
                      <Link href={`/outlook/${t.slug}`}>{t.name}</Link>
                    </h2>
                    <div className="row mt8" style={{ gap: 12 }}>
                      <span className="num" style={{ fontSize: 19, fontWeight: 600 }}>{num(t.spot, 0)}</span>
                      {inst && <Delta v={chg(inst)} />}
                    </div>
                  </div>
                  {inst && <Spark data={inst.hist} w={120} h={38} up={chg(inst) >= 0} />}
                </div>

                <div className="callout mb16" style={{ fontSize: 14.5 }}>{t.modal}</div>

                <div className="grid" style={{ gridTemplateColumns: "minmax(0,1fr) 230px", gap: 24 }}>
                  <div className="min0"><Tree nodes={t.root} /></div>
                  <div>
                    <div className="label mb8">Levels in play</div>
                    <div className="ladder">
                      {t.levels.map((l) => (
                        <div key={l.k} className={l.k === "Spot" ? "spot" : ""} title={l.why}>
                          <span className="lv">{l.v.toLocaleString("en-IN")}</span>
                          <span style={{ color: "var(--muted)" }}>{l.k}</span>
                        </div>
                      ))}
                    </div>
                    <p className="meta mt12">{t.note}</p>
                    <Link href={`/outlook/${t.slug}`} className="chip a mt12"
                      style={{ padding: "7px 12px", fontSize: 12 }}>Full tree →</Link>
                  </div>
                </div>
              </section>
            );
          })}
        </div>

        {/* engine */}
        <section className="band reveal" style={{ paddingBlock: 38 }}>
          <div className="wrap">
            <div className="kicker accent">How the analysis engine works</div>
            <h2 style={{ fontSize: "clamp(24px,3.2vw,36px)", marginTop: 8, maxWidth: 820 }}>
              Models read the news. Code produces the numbers.
            </h2>
            <div className="grid mt24" style={{ gridTemplateColumns: "repeat(auto-fit,minmax(290px,1fr))", gap: 26 }}>
              <div>
                <div className="label mb12">What it does</div>
                {ENGINE.does.map((d) => (
                  <div key={d.h} style={{ marginBottom: 16 }}>
                    <h3 style={{ fontSize: 16 }}>{d.h}</h3>
                    <p className="sub mt4" style={{ fontSize: 13 }}>{d.p}</p>
                  </div>
                ))}
              </div>
              <div>
                <div className="label mb12">What it does not do</div>
                {ENGINE.doesNot.map((d) => (
                  <div key={d.h} style={{ marginBottom: 16 }}>
                    <h3 style={{ fontSize: 16 }}>{d.h}</h3>
                    <p className="sub mt4" style={{ fontSize: 13 }}>{d.p}</p>
                  </div>
                ))}
              </div>
            </div>
          </div>
        </section>

        <div className="mt32">
          <SectionHead title="What the evidence says about levels" />
          <div className="card mb32 reveal">
            <p className="sub" style={{ fontSize: 14.5, maxWidth: 860 }}>{ENGINE.evidence.summary}</p>
            <hr className="mt16 mb12" />
            <ul className="sources">
              {ENGINE.evidence.sources.map((s) => (
                <li key={s.label}><b>{s.who}</b><span>{s.label}</span></li>
              ))}
            </ul>
            <p className="meta mt12">
              We publish the branches because mapping the possibilities is useful even when
              none of them is tradeable as a rule. Knowing that the false-breakout branch is
              the modal outcome after a push through a high-OI strike is worth more than a
              confident arrow.
            </p>
          </div>
        </div>

        <div className="mb32">
          <Notice>
            Branch probabilities are conditional on their parent. Multiply down a path for the
            joint probability — a 42% branch beneath a 34% branch is a 14% outcome, not a 42%
            one. None of this is a recommendation or a trading system.
          </Notice>
        </div>
      </div>
    </>
  );
}
